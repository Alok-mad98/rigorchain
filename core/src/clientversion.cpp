/**
 * Name of client reported in the 'version' message. Report the same name
 * for both rigord and rigor-qt, to make it harder for attackers to
 * target servers or GUI users specifically.
 */
const std::string CLIENT_NAME("RigorCore");


#ifdef HAVE_BUILD_INFO
#include <obj/build.h>
// The <obj/build.h>, which is generated by the build environment (share/genbuild.sh),
// could contain only one line of the following:
//   - "#define BUILD_GIT_TAG ...", if the top commit is tagged
//   - "#define BUILD_GIT_COMMIT ...", if the top commit is not tagged
//   - "// No build information available", if proper git information is not available
#endif

//! git will put "#define GIT_COMMIT_ID ..." on the next line inside archives. $Format:%n#define GIT_COMMIT_ID "%H"$

#ifdef BUILD_GIT_TAG
    #define BUILD_DESC BUILD_GIT_TAG
    #define BUILD_SUFFIX ""
#else
    // Display identity is RIGOR_RELEASE_VERSION (v0.1.1-alphaplus), not PACKAGE_VERSION (25.0.0).
    #define BUILD_DESC RIGOR_RELEASE_VERSION
    #if defined(BUILD_GIT_COMMIT)
        #define BUILD_SUFFIX "-" BUILD_GIT_COMMIT
    #elif defined(GIT_COMMIT_ID)
        #define BUILD_SUFFIX "-g" GIT_COMMIT_ID
    #else
        #define BUILD_SUFFIX ""
    #endif
#endif

static std::string FormatVersion(int nVersion)
{
    return strprintf("%d.%d.%d", nVersion / 10000, (nVersion / 100) % 100, nVersion % 100);
}

std::string FormatGitCommitStamp()
{
#ifdef BUILD_GIT_COMMIT
    return BUILD_GIT_COMMIT;
#elif defined(BUILD_GIT_TAG)
    return BUILD_GIT_TAG;
#elif defined(GIT_COMMIT_ID)
    return GIT_COMMIT_ID;
#else
    return {};
#endif
}

std::string FormatFullVersion()
{
    static const std::string CLIENT_BUILD(BUILD_DESC);
    return CLIENT_BUILD;
}

std::string FormatReleaseIdentity()
{
    std::string out;
    out += "RIGOR version ";
    out += RIGOR_RELEASE_VERSION;
    out += "\n";
    out += RIGOR_RELEASE_CODENAME;
    out += "\n";
    const std::string commit = FormatGitCommitStamp();
    if (!commit.empty()) {
        out += "BUILD_GIT_COMMIT=";
        out += commit;
        out += "\n";
    }
    std::string network = "mainnet";
    try {
        const std::string chain = gArgs.GetChainName();
        if (chain.empty() || chain == "main") {
            network = "mainnet";
        } else if (chain == "test") {
            network = "testnet";
        } else {
            network = chain;
        }
    } catch (...) {
        network = "mainnet";
    }
    out += "NETWORK=";
    out += network;
    out += "\n";
    return out;
}

/**
 * Format the subversion field according to BIP 14 spec (https://github.com/bitcoin/bips/blob/master/bip-0014.mediawiki)
 */
std::string FormatSubVersion(const std::string& name, int nClientVersion, const std::vector<std::string>& comments)
{
    std::ostringstream ss;
    ss << "/";
    ss << name << ":" << FormatVersion(nClientVersion);
    if (!comments.empty())
    {
        std::vector<std::string>::const_iterator it(comments.begin());
        ss << "(" << *it;
        for(++it; it != comments.end(); ++it)
            ss << "; " << *it;
        ss << ")";
    }
    ss << "/";
    return ss.str();
}

std::string CopyrightHolders(const std::string& strPrefix)
{
    const auto copyright_devs = strprintf(_(COPYRIGHT_HOLDERS).translated, COPYRIGHT_HOLDERS_SUBSTITUTION);
    std::string strCopyrightHolders = strPrefix + copyright_devs;

    // Make sure Rigor Core copyright is not removed by accident
    if (copyright_devs.find("Rigor Core") == std::string::npos) {
        strCopyrightHolders += "\n" + strPrefix + "The Rigor Core developers";
    }
    return strCopyrightHolders;
}

std::string LicenseInfo()
{
    // First two project links: https://github.com/rigorchain (About dialog regex turns <url> into anchors).
    static constexpr const char* URL_RIGORCHAIN = "https://github.com/rigorchain";
    const std::string mit_line = strprintf(
        _("Distributed under the MIT software license, see the accompanying file %s or %s").translated,
        "COPYING",
        "<https://opensource.org/licenses/MIT>");

    return std::string(
               "Copyright (C) 2026- The Rigor Core developers.\n"
               "\n"
               "Please contribute if you find ") +
           PACKAGE_NAME +
           " useful. "
           "Visit <" +
           URL_RIGORCHAIN +
           "> for further information about the software.\n"
           "The source code is available from <" +
           std::string(URL_RIGORCHAIN) +
           ">.\n"
           "\n"
           "This is experimental software.\n" +
           mit_line + "\n";
}
