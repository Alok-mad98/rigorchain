RigorByteClass ClassifyRigorByte(unsigned int b)
{
    if (b == RIGOR_MARKER_RES_MINT) return RigorByteClass::RES_MINT_MARKER;
    if (b == RIGOR_MARKER_CONVERGE) return RigorByteClass::CONVERGE_MARKER;
    if (b == RIGOR_MARKER_RETURN) return RigorByteClass::RETURN_MARKER;
    if (b <= RIGOR_PUSHDATA4 || (b >= RIGOR_PUSH_1 && b <= RIGOR_PUSH_16)) {
        return RigorByteClass::DATA_PUSH;
    }
    if (b == RIGOR_BURNED_CVG_CLAIM || b > MAX_OPCODE) {
        return RigorByteClass::INVALID;
    }
    return RigorByteClass::RESERVED_INERT;
}

