#!/usr/bin/env python3
"""TASK-010-D evidence dataset integrity gate. No consensus change."""
from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "audit" / "formal_bridge" / "evidence_theorem_mapping_v1.json"
MATRIX = ROOT / "audit" / "formal_bridge" / "evidence_coverage_matrix.md"
REPORT = ROOT / "audit" / "formal_bridge" / "evidence_quality_report_v1.md"
COLLECT = ROOT / "tools" / "formal_bridge" / "evidence_collector.py"
REPLAY = ROOT / "scripts" / "replay_evidence_dataset.py"
SCHEMA_CHK = ROOT / "scripts" / "check_evidence_schema_v1.py"
FIXTURE = ROOT / "audit" / "formal_bridge" / "evidence_v1" / "fixtures" / "replay_block.json"
TEST_DIR = ROOT / "tests" / "formal_bridge"

REQUIRED_MAP = (
    "invalid_block",
    "invalid_tx",
    "bad_pow",
    "bad_asert",
    "connect",
    "disconnect",
    "restart",
    "reorg",
    "decode",
    "encode",
    "malformed_input",
    "connect_disconnect",
)
REQUIRED_THEOREMS = (
    "validation_soundness",
    "pow_soundness",
    "asert_correctness",
    "utxo_inverse",
    "state_transition_correctness",
    "chain_selection",
    "canonical_decode",
    "connect_disconnect_inverse",
)

schema_ok = False
identity_ok = False
mapping_ok = False
isolation_ok = False
pollution = "UNKNOWN"
errors: list[str] = []


def err(msg: str) -> None:
    errors.append(msg)


def load_col():
    spec = importlib.util.spec_from_file_location("evidence_collector", COLLECT)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def run_unittests(pattern: str) -> bool:
    suite = unittest.defaultTestLoader.discover(str(TEST_DIR), pattern=pattern)
    result = unittest.TextTestRunner(verbosity=1).run(suite)
    return result.wasSuccessful()


def write_report() -> None:
    lines = [
        "# Evidence quality report v1",
        "",
        "Generated by `scripts/check_evidence_dataset.py`. Not a Coq proof.",
        "",
        f"- EVIDENCE_SCHEMA_STATUS = {'PASS' if schema_ok else 'FAIL'}",
        f"- EVIDENCE_IDENTITY_STATUS = {'PASS' if identity_ok else 'FAIL'}",
        f"- THEOREM_MAPPING_STATUS = {'PASS' if mapping_ok else 'FAIL'}",
        f"- A_B_C_ISOLATION = {'PASS' if isolation_ok else 'FAIL'}",
        f"- KERNELINPUT_POLLUTION = {pollution}",
        "",
        "Traceability: Evidence → scenario → future theorem candidate.",
        "Class C / client fields do not enter `KernelInputCandidate`.",
        "",
    ]
    if errors:
        lines.append("## Failures")
        lines.append("")
        for e in errors:
            lines.append(f"- {e}")
        lines.append("")
    REPORT.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    global schema_ok, identity_ok, mapping_ok, isolation_ok, pollution

    schema_ok = subprocess.call([sys.executable, str(SCHEMA_CHK)], cwd=str(ROOT)) == 0
    if not schema_ok:
        err("check_evidence_schema_v1.py failed")

    identity_ok = run_unittests("test_evidence_identity.py")
    if not identity_ok:
        err("test_evidence_identity.py failed")

    mapping_ok = True
    if not MAP.is_file():
        mapping_ok = False
        err("missing evidence_theorem_mapping_v1.json")
    else:
        mapping = json.loads(MAP.read_text())
        for key in REQUIRED_MAP:
            if key not in mapping:
                mapping_ok = False
                err(f"mapping missing {key}")
        theorems = {row.get("future_theorem") for row in mapping.values()}
        for th in REQUIRED_THEOREMS:
            if th not in theorems:
                mapping_ok = False
                err(f"mapping missing theorem {th}")
    if not MATRIX.is_file() or "double spend" not in MATRIX.read_text():
        mapping_ok = False
        err("coverage matrix incomplete")

    col = load_col()
    a = col.create_block_evidence(
        block_hash="aa",
        height=1,
        prev_hash="00",
        nBits=1,
        tx_count=1,
        accept=True,
        source="rpc",
    )
    b = col.create_state_transition_evidence(
        before_utxo_hash="b0",
        operation="disconnect",
        after_utxo_hash="b1",
        source="rpc",
    )
    c = col.create_network_observation(peer_count=2, fork=True, source="node_observer")
    iso = col.isolation_errors(a) + col.isolation_errors(b) + col.validate_evidence_record(c)
    isolation_ok = not iso and "network_context" in c and "network_context" not in a
    if not isolation_ok:
        err("A/B/C isolation failed: " + "; ".join(iso))

    leaked = col.candidate_pollution({"ki_pow_ok": True, "peer_count": 1})
    clean = col.candidate_pollution({"ki_pow_ok": True, "ki_asert_ok": True})
    pollution = "NONE" if leaked and not clean else "DETECTED"
    if pollution != "NONE":
        err("KernelInputCandidate pollution check failed")

    if subprocess.call([sys.executable, str(REPLAY), str(FIXTURE)], cwd=str(ROOT)) != 0:
        err("replay_evidence_dataset.py failed")

    if not run_unittests("test_evidence_dataset.py"):
        err("test_evidence_dataset.py failed")

    write_report()
    print(f"EVIDENCE_SCHEMA_STATUS = {'PASS' if schema_ok else 'FAIL'}")
    print(f"EVIDENCE_IDENTITY_STATUS = {'PASS' if identity_ok else 'FAIL'}")
    print(f"THEOREM_MAPPING_STATUS = {'PASS' if mapping_ok else 'FAIL'}")
    print(f"A_B_C_ISOLATION = {'PASS' if isolation_ok else 'FAIL'}")
    print(f"KERNELINPUT_POLLUTION = {pollution}")
    if errors:
        for e in errors:
            print(" -", e)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
