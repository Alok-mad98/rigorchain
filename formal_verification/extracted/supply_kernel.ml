  (&&)
    ((&&)
      ((&&) ((&&) (negb d.bd_has_invalid) (amounts_nonneg d))
        (mint_respects_authorization d)) (ordinary_cannot_credit_mint d))
    (Z.leb d.bd_valid_mint (mint_cap_at d.bd_height))

