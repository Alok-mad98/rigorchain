#!/usr/bin/env python3
"""Generate release/FinalProofInventory.md deterministically.

Audit finding C-3. The inventory was produced once by a throwaway
script that was never committed, so nothing could reproduce it. The
frozen SourceManifest.sha256 recorded a hash of an intermediate copy
that exists in no commit, and the package failed its own integrity
gate.

Inputs, all committed:

  release/TheoremClassification.md   category, file and domain
  release/inventory_metadata.json    per-theorem prose
  mutation/*.sh                      mutation coverage, parsed from
                                     the run_mutation calls themselves

Same inputs in, same bytes out. `--check` regenerates into memory and
byte-compares, which is what CI runs; the document can no longer drift
from the sources it describes.

Category A rows must carry a statement and an assumptions note. A row
promoted to A without prose fails here rather than shipping empty.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
CLASSIFICATION = ROOT / "release" / "TheoremClassification.md"
METADATA = ROOT / "release" / "inventory_metadata.json"
TARGET = ROOT / "release" / "FinalProofInventory.md"
MUTATION_DIR = ROOT / "mutation"

ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|\s*([^|]*?)\s*\|\s*$")
SECTION = re.compile(r"^##+\s+(?:Category|Class)\s+([ABC])\b", re.I)
RUN_MUTATION = re.compile(r"^run_mutation\s+(M\d+)\s+([A-Za-z_][A-Za-z0-9_]*)",
                          re.M)

CLAIM_LEVEL = {"A": "public", "B": "supporting", "C": "boundary"}
CATEGORY_TITLE = {
    "A": "Category A — core verified consensus invariant",
    "B": "Category B — supporting mathematical lemma",
    "C": "Category C — boundary / documentation lemma",
}

PREAMBLE = """# Final Proof Inventory

Generated by `release/gen_final_proof_inventory.py` from
`release/TheoremClassification.md`, `release/inventory_metadata.json`
and the `run_mutation` calls in `mutation/`. Do not edit by hand: CI
regenerates this file and byte-compares it.

This file lists every classified `Theorem` (Category A/B/C) with
enough detail for an adversarial third-party audit.

**Public claim (unchanged):**

Formally verified critical consensus invariants
inside a Coq consensus kernel model,
with explicit extraction and runtime trust boundaries.

`Print Assumptions` for every Category A/B/C row: **Closed under the
global context**. Category C is documentation / non-claim; it is not
invariant evidence.
"""

TAIL = """
Unclassified names in the cone live in
`release/UnclassifiedAllowlist.md` and are **not** public-claim
theorems.

Assumptions column: Coq `Print Assumptions` is Closed. Remaining
*modelling* hypotheses (abstract `H`, C-4 draw bit, extraction
correctness, compiler) are written in prose so they cannot hide.
"""


def read_classification() -> list[tuple[str, str, str, str]]:
    """[(name, file, domain, category)] in table order, deduplicated."""
    cat = None
    seen: set[tuple[str, str]] = set()
    rows: list[tuple[str, str, str, str]] = []
    for line in CLASSIFICATION.read_text().splitlines():
        m = SECTION.match(line.strip())
        if m:
            cat = m.group(1).upper()
            continue
        m = ROW.match(line)
        if not m or cat is None or m.group(1) == "Theorem":
            continue
        name, rel, domain = m.group(1), m.group(2), m.group(3)
        if (name, rel) in seen:
            continue
        seen.add((name, rel))
        rows.append((name, rel, domain, cat))
    return rows


def mutation_coverage() -> dict[str, list[str]]:
    cover: dict[str, list[str]] = {}
    for p in sorted(MUTATION_DIR.glob("*.sh")):
        for mid, thm in RUN_MUTATION.findall(p.read_text()):
            cover.setdefault(thm, []).append(mid)
    for thm in cover:
        cover[thm] = sorted(set(cover[thm]), key=lambda s: int(s[1:]))
    return cover


def render() -> str:
    rows = read_classification()
    meta = json.loads(METADATA.read_text())
    cover = mutation_coverage()

    counts = {c: sum(1 for r in rows if r[3] == c) for c in "ABC"}
    out = [PREAMBLE]
    # Machine-readable markers. CI reads these instead of a number
    # typed into a second file, so the two cannot disagree.
    out += [
        "```",
        f"THEOREM_COUNT={len(rows)}",
        f"CATEGORY_A_COUNT={counts['A']}",
        f"CATEGORY_B_COUNT={counts['B']}",
        f"CATEGORY_C_COUNT={counts['C']}",
        "MATURITY_LEVEL=4.9",
        "```",
        "",
        "Maturity level 4.9 is defined in `release/LevelDefinition.md`. It is",
        "the only level statement in the package; no other document assigns",
        "a level.",
        "",
        "| Class | Count | Claim level |",
        "|---|---|---|",
    ]
    for c in "ABC":
        out.append(f"| {c} | {counts[c]} | {CLAIM_LEVEL[c]} |")
    out.append(f"| **Total classified** | **{len(rows)}** | |")
    out.append(TAIL)

    problems: list[str] = []
    for cat in "ABC":
        out.append(f"## {CATEGORY_TITLE[cat]}")
        out.append("")
        for name, rel, domain, c in rows:
            if c != cat:
                continue
            m = meta.get(f"{name}|{rel}", {})
            statement = m.get("statement", "").strip()
            assumptions = m.get("assumptions", "").strip()
            if cat == "A" and not (statement and assumptions):
                problems.append(
                    f"Category A row {name} ({rel}) has no statement/assumptions "
                    f"in release/inventory_metadata.json")
            muts = cover.get(name, [])
            out += [
                f"### {name}",
                "",
                f"- **Name:** `{name}`",
                f"- **File:** `{rel}`",
                f"- **Category:** {c}",
                f"- **Domain:** {domain}",
                f"- **Statement:** {statement or 'TODO'}",
                f"- **Assumptions:** {assumptions or 'TODO'}",
                f"- **Dependencies:** {m.get('dependencies', '').strip() or 'n/a'}",
                "- **Mutation Coverage:** " + (", ".join(muts) if muts
                                               else "none (see MutationCompletenessAudit.md)"),
                f"- **Claim Level:** {CLAIM_LEVEL[c]}",
                f"- **Meaning:** {m.get('meaning', '').strip() or 'n/a'}",
                "",
            ]
    if problems:
        for p in problems:
            print("FAIL: " + p, file=sys.stderr)
        sys.exit(f"{len(problems)} Category A row(s) missing prose")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="regenerate in memory and byte-compare")
    args = ap.parse_args()

    text = render()
    if args.check:
        current = TARGET.read_text() if TARGET.is_file() else ""
        if current != text:
            print("FAIL: release/FinalProofInventory.md is not what "
                  "release/gen_final_proof_inventory.py produces.",
                  file=sys.stderr)
            print("      Run: python3 release/gen_final_proof_inventory.py",
                  file=sys.stderr)
            return 1
        n = text.count("\n### ")
        print(f"FINAL_PROOF_INVENTORY_REPRODUCIBLE=TRUE entries={n}")
        return 0

    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)} entries={text.count(chr(10) + '### ')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
