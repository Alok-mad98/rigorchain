#!/usr/bin/env python3
"""Regenerate release/UnclassifiedAllowlist.md from the source tree.

Audit finding M-2: the reverse classification scan used to cover only
Kernel/ and proofs/. Widening it to the whole cone made 70 further
theorems visible to governance. They are listed here rather than
promoted, so that the Category A name-set stays the thing the public
claim rests on.

Deterministic: same tree in, same bytes out. CI regenerates and
byte-compares, so the list cannot drift from the sources.
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

SKIP_PARTS = ("archive", "_build", "mutation", "extraction", "extracted", "certicoq")
THM = re.compile(r"^(?:Theorem|Corollary)\s+(\w+)", re.M)
ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|")

HEADER = """# Unclassified Allowlist

Theorem / Corollary names in the kernel cone that are **intentionally**
not in Category A/B/C of either classification table. CI
(`scripts/check_theorem_classification.py`) fails if any name in the
cone is missing from both the tables and this list.

This is an inventory, not a promotion. Do not cite these as
Category-A invariants.

Generated by `release/gen_unclassified_allowlist.py`. Do not edit by
hand: CI regenerates this file and byte-compares it.

Scope note: until the P0-130 audit this reverse check covered only
`Kernel/` and `proofs/`, so names outside those two directories were
invisible to it. The scan now walks the whole cone.
"""


def classified_names() -> set[str]:
    names: set[str] = set()
    for rel in ("release/TheoremClassification.md",
                "evidence/TheoremClassification.md"):
        p = ROOT / rel
        if not p.is_file():
            continue
        for line in p.read_text().splitlines():
            m = ROW.match(line)
            if m and m.group(1) != "Theorem":
                names.add(m.group(1))
    return names


def main() -> int:
    classified = classified_names()
    by_file: dict[str, list[str]] = {}
    for p in sorted(ROOT.rglob("*.v")):
        if any(x in p.parts for x in SKIP_PARTS):
            continue
        rel = p.relative_to(ROOT).as_posix()
        for m in THM.finditer(p.read_text()):
            if m.group(1) not in classified:
                by_file.setdefault(rel, []).append(m.group(1))

    lines = [HEADER, ""]
    total = 0
    for rel in sorted(by_file):
        for name in sorted(set(by_file[rel])):
            lines.append(f"{name}  {rel}")
            total += 1
    lines.append("")
    lines.append(f"<!-- entries: {total} -->")
    out = ROOT / "release" / "UnclassifiedAllowlist.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)} entries={total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
