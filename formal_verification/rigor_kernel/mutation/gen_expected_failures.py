#!/usr/bin/env python3
"""Generate mutation/expected_failures.md from the mutation scripts.

This file used to be written by hand. It went stale twice over: it
stopped at M50 while the suite grew to M76, and several rows still
named theorems the mutant had been retargeted away from. A hand-kept
list of what a mutant is supposed to break is exactly the artifact the
P0-130 audit found untrustworthy, so it is derived now.

The declared theorem names are what `run_mutation` is called with, and
`mutation/lib.sh` verifies at run time that those are the proofs that
actually fail. Between the two, nothing in this table can drift from
the suite without CI noticing.
"""
from __future__ import annotations

import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MUT = ROOT / "mutation"

FAMILY = re.compile(r"^mutate_(.*)\.sh$")


def family(script: pathlib.Path) -> str:
    m = FAMILY.match(script.name)
    stem = m.group(1) if m else script.stem
    return stem.replace("_", " ").title()


def cell(text: str) -> str:
    """Make a mutation fragment safe and readable inside a table cell."""
    text = re.sub(r"\s+", " ", text.strip()).replace("|", r"\|")
    if len(text) > 60:
        text = text[:57] + "..."
    return f"`{text}`" if text else "*(empty)*"


def declarations() -> list[tuple[int, str, str, str, str, str]]:
    """Ask the scripts themselves what they declare.

    Reading the calls with a regex got a third of them wrong, because
    the arguments are shell-quoted and some span lines. Bash already
    knows how to unquote them, so the harness has a list-only mode and
    this just runs it.
    """
    rows = []
    env = dict(os.environ, MUTATION_LIST_ONLY="1")
    for script in sorted(MUT.glob("mutate_*.sh")):
        out = subprocess.run(["bash", str(script)], env=env, cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            if not line.startswith("MUTATION_DECL\t"):
                continue
            _, mid, names, rel, old, new = line.split("\t")
            rows.append((int(mid[1:]), mid, family(script),
                         f"{cell(old)} → {cell(new)}", f"`{rel}`",
                         ", ".join(f"`{n}`" for n in names.split())))
    rows.sort()
    return rows


def main() -> int:
    rows = declarations()
    if not rows:
        sys.exit("gen_expected_failures: no run_mutation calls found")
    ids = [r[0] for r in rows]
    if len(set(ids)) != len(ids):
        dup = sorted({i for i in ids if ids.count(i) > 1})
        sys.exit(f"gen_expected_failures: duplicate ids {dup}")

    out = [
        "# Expected mutation failures",
        "",
        "Generated by `mutation/gen_expected_failures.py`. Do not edit by",
        "hand: CI regenerates this file and byte-compares it.",
        "",
        "Each row is a mutation the suite applies and the theorem it is",
        "declared to break. The declaration is not taken on trust:",
        "`mutation/lib.sh` isolates each mutant, reads the first failing",
        "proof out of the compile log, admits it, and repeats until the",
        "declared theorem itself fails. A mutant that cannot be shown to",
        "kill what it names is reported as `mutation_mismatch`.",
        "",
        f"`MUTATION_COUNT={len(rows)}`",
        "",
        "| ID | Family | Incorrect rule | File mutated | Theorem that must fail |",
        "|---|---|---|---|---|",
    ]
    for _, mid, fam, change, rel, names in rows:
        out.append(f"| {mid} | {fam} | {change} | {rel} | {names} |")
    out.append("")

    dest = MUT / "expected_failures.md"
    dest.write_text("\n".join(out))
    print(f"wrote {dest.relative_to(ROOT)} mutations={len(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
