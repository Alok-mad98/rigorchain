#!/usr/bin/env python3
"""Gate: every Category B theorem is a checked deferral or has a mutant.

Category B is defined by `release/TheoremClassification.md` as a
supporting lemma, and the reason such a lemma may ship without a
mutant is written in `check_mutation_coverage.py`: its proof forwards
to results that are themselves covered, so no mutation of any
definition can make it fail. Frontier item 1.4 states the same thing
about the classifier lemmas.

That reason was never measured. Applying the deferral test from
`check_mutation_coverage.py` to Category B found it holds for 15 of
106 names. The other 91 proofs rewrite, compute and do arithmetic,
and nothing checks that the work they do is non-trivial. Among them
are the extraction source-identity results, the CertiCoq surface
equalities, and every non-vacuity witness in the chain cone — the
statements an adversarial reader attacks first, and the ones a
`classify_script s = classify_script s` would hide behind.

This gate does not demand that the 91 be fixed at once. It pins them
in `release/CategoryBCoverageDebt.md` and fails when the set changes
in either direction, so the debt is visible, cannot grow silently,
and each name leaves the file only by being classified correctly or
by getting a mutant.

Usage:
    python3 scripts/check_category_b_coverage.py          # gate
    python3 scripts/check_category_b_coverage.py --write  # regenerate
"""
from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from check_mutation_coverage import (            # noqa: E402
    ROOT,
    collect_proofs,
    declared_targets,
    deferral_components,
    read_source,
    source_files,
)

DEBT = ROOT / "release/CategoryBCoverageDebt.md"

HEADER = """# Category B Coverage Debt

Category B theorems whose proof does real work and which no mutation
is known to break. Category B is allowed to ship without a mutant
only when its proof is a checked deferral to covered results; these
are the names for which that is not true.

Generated by `scripts/check_category_b_coverage.py`. Do not edit by
hand: CI regenerates this file and compares the set. A name leaves
this file by being reclassified (it was Category A or C all along) or
by getting a mutation that kills it. A new name appearing here fails
the gate.

This is debt, not an exemption. Nothing listed here has been shown to
be non-trivial.

The last column splits the list by how much is known, because
"untested" covers two different situations and reading them as one
overstates the first and understates the second:

  cites-only-tested-lemmas
      Every lemma this proof names is itself killed by a mutant or
      reduces to lemmas that are. The step this proof takes on top of
      them is what nothing tests. For several of these the kill-set
      run showed the proof surviving a mutant only after the lemma
      below it was admitted, which is what a forwarding proof does --
      but the proof uses `rewrite`, `tauto` or `exfalso`, tactics that
      can close a goal, so it is not a checked deferral and is not
      exempt.

  nothing-known
      The proof reaches its conclusion through lemmas that are
      themselves untested, or through arithmetic of its own. No
      mutation is known to break any part of it.

"""


def category(letter: str) -> set[str]:
    """Names listed under `## Category <letter>` in the classification."""
    text = (ROOT / "release/TheoremClassification.md").read_text()
    start = text.find(f"## Category {letter}")
    if start < 0:
        sys.exit(f"check_category_b_coverage: no Category {letter} table")
    rest = text[start + 1:]
    stop = re.search(r"^## ", rest, re.M)
    body = rest[:stop.start()] if stop else rest
    return {m.group(1)
            for m in re.finditer(r"^\|\s*`([^`]+)`\s*\|", body, re.M)
            if m.group(1) != "Theorem"}


CITED = re.compile(r"\b(?:exact|e?apply|rewrite|destruct|pose proof|"
                   r"specialize|unfold)\s+\(?\s*"
                   r"(?:[A-Za-z_][A-Za-z0-9_']*\.)*([A-Za-z_][A-Za-z0-9_']*)")


def bare_set(detail: bool = False):
    """Category B names that are neither mutant-killed nor a deferral.

    With `detail`, also returns for each bare name whether every lemma
    it cites is itself covered. That does not make it covered -- the
    step it takes on top of those lemmas is still untested -- but it
    separates a proof standing on tested ground from one standing on
    nothing.
    """
    cat_b = category("B")
    named = declared_targets()
    proofs, known = collect_proofs()

    resolving: set[str] = set()
    memo: dict[str, bool] = {}

    def covered(name: str) -> bool:
        if name in named:
            return True
        if name in memo:
            return memo[name]
        if name in resolving:          # a cycle proves nothing
            return False
        resolving.add(name)
        components = deferral_components(proofs.get(name, ""), known)
        ok = bool(components) and all(covered(c) for c in components)
        resolving.discard(name)
        memo[name] = ok
        return ok

    bare, by_mutant, by_deferral = set(), 0, 0
    for name in sorted(cat_b):
        if name in named:
            by_mutant += 1
        elif covered(name):
            by_deferral += 1
        else:
            bare.add(name)
    if not detail:
        return bare, by_mutant, by_deferral

    standing: dict[str, str] = {}
    for name in bare:
        cited = {c for c in CITED.findall(proofs.get(name, ""))
                 if c in known and c != name}
        standing[name] = ("cites-only-tested-lemmas"
                          if cited and all(covered(c) for c in cited)
                          else "nothing-known")
    return bare, by_mutant, by_deferral, standing


def recorded() -> set[str]:
    if not DEBT.exists():
        return set()
    return {line.split()[0]
            for line in DEBT.read_text().splitlines()
            if line and not line.startswith(("#", " ")) and "  " in line}


DECLARED = re.compile(
    r"^\s*(?:Theorem|Lemma|Corollary|Remark|Fact|Example|Proposition)\s+"
    r"([A-Za-z_][A-Za-z0-9_']*)", re.M)


def render(bare: set[str], standing: dict[str, str]) -> str:
    lines = [HEADER]
    where: dict[str, str] = {}
    for path in source_files():
        for m in DECLARED.finditer(read_source(path)):
            where.setdefault(m.group(1), str(path.relative_to(ROOT)))
    for name in sorted(bare):
        lines.append(f"{name}  {where.get(name, 'UNKNOWN')}  "
                     f"{standing.get(name, 'nothing-known')}")
    return "\n".join(lines) + "\n"


def main() -> int:
    write = "--write" in sys.argv
    bare, by_mutant, by_deferral, standing = bare_set(detail=True)
    cites = sum(1 for s in standing.values()
                if s == "cites-only-tested-lemmas")

    print(f"CATEGORY_B_TOTAL={by_mutant + by_deferral + len(bare)}")
    print(f"CATEGORY_B_KILLED_DIRECTLY={by_mutant}")
    print(f"CATEGORY_B_COVERED_BY_DEFERRAL={by_deferral}")
    print(f"CATEGORY_B_UNCHECKED={len(bare)}")
    print(f"CATEGORY_B_UNCHECKED_ON_TESTED_LEMMAS={cites}")
    print(f"CATEGORY_B_UNCHECKED_NOTHING_KNOWN={len(bare) - cites}")

    if write:
        DEBT.write_text(render(bare, standing))
        print(f"WROTE {DEBT.relative_to(ROOT)}")
        return 0

    listed = recorded()
    new = sorted(bare - listed)
    stale = sorted(listed - bare)
    if new:
        print("FAIL: Category B theorems doing real work with no mutant, "
              "not recorded as debt:", file=sys.stderr)
        for name in new:
            print(f"  {name}", file=sys.stderr)
    if stale:
        print("FAIL: recorded debt that is no longer bare; rerun with "
              "--write to retire it:", file=sys.stderr)
        for name in stale:
            print(f"  {name}", file=sys.stderr)
    if new or stale:
        return 1

    print("CATEGORY_B_COVERAGE=RECORDED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
