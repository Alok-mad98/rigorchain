#!/usr/bin/env python3
"""Emit VectorAgreement.v from P0-024 golden JSON. Do not hand-edit the .v."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VEC = Path(__file__).resolve().parent
CLASS = json.loads((VEC / "rigor_classification_vectors.json").read_text(encoding="utf-8"))
SIGHASH = json.loads((VEC / "rigor_sighash_vectors.json").read_text(encoding="utf-8"))

COQ_ASSET = {
    "ORU": "AssetORU",
    "RES": "AssetRES",
    "NONE": "AssetNone",
    "INVALID": "AssetInvalid",
}

TAG_LEMMA = {
    "ORU": "tag_oru",
    "RES": "tag_res",
    "RES_MINT": "tag_mint",
}


def ident(name: str) -> str:
    return name.replace("-", "_")


def bytes_to_coq(data: bytes, indent: str = "  ") -> str:
    if not data:
        return "nil"
    nums = [str(b) for b in data]
    lines = []
    for i in range(0, len(nums), 16):
        chunk = "; ".join(nums[i : i + 16])
        prefix = indent if i == 0 else indent
        lines.append(prefix + chunk)
    body = ";\n".join(lines)
    return f"[\n{body}\n{indent}]%nat"


def main() -> None:
    parts = [
        "(* AUTO-GENERATED by formal_verification/vectors/gen_vector_agreement.py — DO NOT EDIT.",
        "   P0-024 finite vector lock. Not a ∀ C++ refinement.",
        "   refinement_proved remains false. *)",
        "From Coq Require Import List.",
        "From Coq Require Import Arith.PeanoNat.",
        "Import ListNotations.",
        "Require Import RigorV01.AssetClassification.",
        "Require Import RigorV01.SignatureDomainSeparation.",
        "From Rigor Require Import RigorHash.",
        "",
        "Local Open Scope nat_scope.",
        "",
        "(** * Classification vectors — classify(script) = golden AssetType *)",
        "",
    ]

    class_lemmas = []
    for row in CLASS:
        name = ident(row["name"])
        spk = bytes.fromhex(row["scriptPubKey"]) if row["scriptPubKey"] else b""
        expected = COQ_ASSET[row["expected"]]
        parts.append(f"Definition vec_{name}_spk : list byte := {bytes_to_coq(spk)}.")
        parts.append("")
        lemma = f"vec_{name}_classify"
        parts.append(f"Lemma {lemma} : classify vec_{name}_spk = {expected}.")
        parts.append("Proof. vm_compute. reflexivity. Qed.")
        parts.append("")
        class_lemmas.append(lemma)

    parts.append("Theorem classification_vectors_agree :")
    conj = " /\\\n  ".join(f"{lem}" for lem in class_lemmas)
    # That's wrong - we need the statements not the lemma names as props
    # Better: conjunction of classify equalities, proved by applying lemmas.

    # Reset the last theorem approach:
    parts[-1] = "Theorem classification_vectors_agree :"
    eqs = []
    for row in CLASS:
        name = ident(row["name"])
        expected = COQ_ASSET[row["expected"]]
        eqs.append(f"classify vec_{name}_spk = {expected}")
    parts.append("  " + " /\\\n  ".join(eqs) + ".")
    parts.append("Proof.")
    if len(class_lemmas) == 1:
        parts.append(f"  apply {class_lemmas[0]}.")
    else:
        # split; [apply L1 | split; [apply L2 | ...]]
        applies = class_lemmas
        tactic = "apply " + applies[-1]
        for lem in reversed(applies[:-1]):
            tactic = f"split; [apply {lem}| {tactic}]"
        parts.append(f"  {tactic}.")
    parts.append("Qed.")
    parts.append("")
    parts.append("(** * Sighash vectors — domain tag prefix + SHA256d(preimage) = golden digest *)")
    parts.append("")

    hash_lemmas = []
    tag_lemmas = []
    for row in SIGHASH:
        name = ident(row["asset"].lower())
        pre = bytes.fromhex(row["preimage"])
        digest = bytes.fromhex(row["expected_hash"])
        tag = TAG_LEMMA[row["asset"]]
        parts.append(f"Definition vec_{name}_preimage : list byte := {bytes_to_coq(pre)}.")
        parts.append("")
        parts.append(f"Definition vec_{name}_digest : list byte := {bytes_to_coq(digest)}.")
        parts.append("")
        tlem = f"vec_{name}_preimage_tag"
        parts.append(f"Lemma {tlem} : firstn 8 vec_{name}_preimage = {tag}.")
        parts.append("Proof. vm_compute. reflexivity. Qed.")
        parts.append("")
        hlem = f"vec_{name}_hash"
        parts.append(f"Lemma {hlem} : hash256_bytes vec_{name}_preimage = vec_{name}_digest.")
        parts.append("Proof. vm_compute. reflexivity. Qed.")
        parts.append("")
        tag_lemmas.append(tlem)
        hash_lemmas.append(hlem)

    parts.append("Theorem sighash_tag_vectors_agree :")
    tag_eqs = []
    for row in SIGHASH:
        name = ident(row["asset"].lower())
        tag = TAG_LEMMA[row["asset"]]
        tag_eqs.append(f"firstn 8 vec_{name}_preimage = {tag}")
    parts.append("  " + " /\\\n  ".join(tag_eqs) + ".")
    parts.append("Proof.")
    tactic = "apply " + tag_lemmas[-1]
    for lem in reversed(tag_lemmas[:-1]):
        tactic = f"split; [apply {lem}| {tactic}]"
    parts.append(f"  {tactic}.")
    parts.append("Qed.")
    parts.append("")
    parts.append("Theorem sighash_hash_vectors_agree :")
    hash_eqs = []
    for row in SIGHASH:
        name = ident(row["asset"].lower())
        hash_eqs.append(f"hash256_bytes vec_{name}_preimage = vec_{name}_digest")
    parts.append("  " + " /\\\n  ".join(hash_eqs) + ".")
    parts.append("Proof.")
    tactic = "apply " + hash_lemmas[-1]
    for lem in reversed(hash_lemmas[:-1]):
        tactic = f"split; [apply {lem}| {tactic}]"
    parts.append(f"  {tactic}.")
    parts.append("Qed.")
    parts.append("")

    dest = ROOT / "formal_verification" / "rigor_v01" / "VectorAgreement.v"
    dest.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
