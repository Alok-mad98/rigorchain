#!/usr/bin/env python3
"""
RIGOR CONSENSUS DIFFERENTIAL FUZZING FRAMEWORK
=============================================

Randomised differential testing of the Rigor consensus kernel.

WHAT THIS ACTUALLY COMPARES
---------------------------
  Layer 1 (Python executable spec)  : formal_verification/spec/rigor_consensus_spec.py
  Layer 2 (Coq kernel, via coqc)    : formal_verification/coq/{ConvergeRoot,SigmaCR01}.v
  Layer 3 (C++ production code)     : NOT WIRED unless RIGOR_CPP_HARNESS is set

The Coq leg is a genuinely independent implementation: random inputs are
compiled into a Coq source file and evaluated by the Coq kernel's VM
(`vm_compute`), including a byte-level SHA-256 written in Coq. Python's
hashlib is not involved on that side.

HISTORY / WHY THIS FILE WAS REWRITTEN (SECURITY-001-F, finding F-2)
-------------------------------------------------------------------
The previous version of this file defined `_call_cpp_*` and `_call_coq_*`
helpers that all simply returned the *Python* result:

    def _call_cpp_convergence_root(self, txids):
        # For now, return the Python output (assume C++ matches)
        return compute_convergence_root_from_txids(txids)

so every comparison degenerated to `x == x and x == x` and passed for all
iterations by construction. It could not fail, yet project documentation cited
it as "ANY MISMATCH = CONSENSUS FAILURE" evidence of three-way equivalence.

This version cannot pass vacuously:
  * A leg that is not wired is reported UNAVAILABLE and never counted as passing.
  * If no independent oracle is available at all, the run exits INCONCLUSIVE
    (exit code 2) rather than printing success.
  * Any genuine mismatch exits 1.

Exit codes: 0 = compared and agreed, 1 = MISMATCH, 2 = inconclusive/no oracle.
"""

from __future__ import annotations

import os
import random
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, List, Optional

REPO_FV = Path(__file__).resolve().parents[1]
COQ_DIR = REPO_FV / "coq"

sys.path.insert(0, str(REPO_FV / "spec"))
from rigor_consensus_spec import (  # noqa: E402
    TXID_SIZE,
    compute_convergence_root_from_txids,
    compute_sigma_hash,
)


# =============================================================================
# RANDOM INPUT GENERATION
# =============================================================================


class RandomGenerator:
    """Generate random consensus inputs for fuzzing."""

    def __init__(self, seed: Optional[int] = None):
        self.rng = random.Random(seed)

    def random_bytes(self, length: int) -> bytes:
        return bytes(self.rng.getrandbits(8) for _ in range(length))

    def random_txid(self) -> bytes:
        return self.random_bytes(TXID_SIZE)

    def random_height(self) -> int:
        return self.rng.randint(0, 10_000_000)

    def random_target(self) -> int:
        return self.rng.randint(0, 0xFFFFFFFF)


# =============================================================================
# COQ ORACLE (Layer 2) — genuinely independent implementation
# =============================================================================


def _coq_bytes(b: bytes) -> str:
    """bytes -> Coq `list byte` literal."""
    return "[" + ";".join(str(x) for x in b) + "]%nat"


def _coq_bytes_list(bs: List[bytes]) -> str:
    return "[" + ";".join(_coq_bytes(b) for b in bs) + "]"


COQ_PREAMBLE = """(* AUTO-GENERATED by fuzz/differential_fuzzer.py. Ephemeral. *)
Require Import Coq.ZArith.ZArith.
Require Import Coq.Lists.List.
Import ListNotations.
Require Import Types.
From Rigor Require Import RigorBytes.
Include RigorBytes.
Require Import RigorHash.
Require Import SigmaCR01.
Require Import ConvergeRoot.

Open Scope Z_scope.

Fixpoint blist_eq (a b : list nat) : bool :=
  match a, b with
  | nil, nil => true
  | x :: xs, y :: ys => andb (Nat.eqb x y) (blist_eq xs ys)
  | _, _ => false
  end.
"""

_RESULT_RE = re.compile(r"\((\d+)%nat,\s*(true|false)\)")


class CoqOracleUnavailable(RuntimeError):
    pass


class CoqOracle:
    """Evaluates the Coq consensus kernel on concrete inputs via `coqc`.

    Cases are batched into one Coq file: a `coqc` invocation costs seconds, so
    per-case invocation would make the fuzzer unusable.
    """

    def __init__(self, coq_dir: Path = COQ_DIR):
        self.coq_dir = coq_dir
        if shutil.which("coqc") is None:
            raise CoqOracleUnavailable("coqc not found on PATH")
        # The kernel modules must already be compiled (`make` in coq/).
        for required in ("ConvergeRoot.vo", "SigmaCR01.vo", "RigorHash.vo"):
            if not (coq_dir / required).is_file():
                raise CoqOracleUnavailable(
                    f"{required} not built; run `make` in {coq_dir} first"
                )

    def evaluate(self, checks: List[str]) -> List[bool]:
        """Run `blist_eq`-style boolean checks; returns them in order.

        Each entry of `checks` is a Coq expression of type `bool` asserting that
        the Coq-computed value equals the Python-computed value.
        """
        if not checks:
            return []
        lines = [COQ_PREAMBLE]
        for i, expr in enumerate(checks):
            lines.append(f"Compute ({i}%nat, {expr}).")
        source = "\n".join(lines) + "\n"

        with tempfile.TemporaryDirectory() as tmp:
            vfile = Path(tmp) / "RigorFuzzProbe.v"
            vfile.write_text(source, encoding="utf-8")
            proc = subprocess.run(
                ["coqc", "-q", "-R", str(self.coq_dir), "Rigor", str(vfile)],
                capture_output=True,
                text=True,
                cwd=str(self.coq_dir),
            )
        if proc.returncode != 0:
            raise CoqOracleUnavailable(
                f"coqc failed (exit {proc.returncode}):\n{proc.stderr[-2000:]}"
            )

        found = {int(idx): (val == "true") for idx, val in _RESULT_RE.findall(proc.stdout)}
        missing = [i for i in range(len(checks)) if i not in found]
        if missing:
            raise CoqOracleUnavailable(
                f"coqc produced no result for case(s) {missing[:5]}"
            )
        return [found[i] for i in range(len(checks))]


# =============================================================================
# C++ ORACLE (Layer 3) — only if a harness binary is provided
# =============================================================================


class CppOracle:
    """Placeholder for a real C++ harness.

    Deliberately NOT implemented by delegating to Python. If
    `RIGOR_CPP_HARNESS` is unset, the C++ leg reports UNAVAILABLE and is
    excluded from the comparison rather than silently agreeing with Python.
    """

    def __init__(self) -> None:
        self.binary = os.environ.get("RIGOR_CPP_HARNESS")
        if not self.binary or not Path(self.binary).is_file():
            raise CoqOracleUnavailable(
                "RIGOR_CPP_HARNESS not set to an existing binary; C++ leg not wired"
            )


# =============================================================================
# DIFFERENTIAL TESTING
# =============================================================================


@dataclass
class Mismatch:
    test_name: str
    case_index: int
    inputs: str


@dataclass
class DifferentialReport:
    compared: int = 0
    mismatches: List[Mismatch] = field(default_factory=list)
    unavailable: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.mismatches

    @property
    def conclusive(self) -> bool:
        return self.compared > 0


class DifferentialFuzzer:
    """Compare the Python spec against every independent oracle available."""

    def __init__(self, iterations: int = 32, seed: Optional[int] = None):
        self.iterations = iterations
        self.generator = RandomGenerator(seed)
        self.report = DifferentialReport()

    # -- case builders: each returns (coq_check_expr, description) ------------

    def _case_convergence_root(self) -> tuple[str, str]:
        n = self.generator.rng.randint(0, 12)
        txids = [self.generator.random_txid() for _ in range(n)]
        expected = compute_convergence_root_from_txids(txids)
        expr = (
            f"blist_eq (convergence_root_from_txid_bytes {_coq_bytes_list(txids)}) "
            f"{_coq_bytes(expected)}"
        )
        return expr, f"ConvergenceRoot(n={n})"

    def _case_sigma(self) -> tuple[str, str]:
        txid = self.generator.random_txid()
        bind = self.generator.random_txid()
        croot = self.generator.random_txid()
        height = self.generator.random_height()
        target_prev = self.generator.random_target()
        expected = compute_sigma_hash(txid, bind, height, target_prev, croot)
        expr = (
            f"blist_eq (sigma_bytes {_coq_bytes(txid)} {_coq_bytes(croot)} "
            f"{_coq_bytes(bind)} {height} {target_prev}) {_coq_bytes(expected)}"
        )
        return expr, f"SigmaCR01(height={height},target_prev={target_prev})"

    # -- driver ---------------------------------------------------------------

    def run(self) -> DifferentialReport:
        print("=" * 70)
        print("RIGOR CONSENSUS DIFFERENTIAL FUZZING")
        print("=" * 70)

        builders: List[Callable[[], tuple[str, str]]] = [
            self._case_convergence_root,
            self._case_sigma,
        ]

        checks: List[str] = []
        descriptions: List[str] = []
        names: List[str] = []
        for _ in range(self.iterations):
            for build in builders:
                expr, desc = build()
                checks.append(expr)
                descriptions.append(desc)
                names.append(desc.split("(")[0])

        # --- Layer 3: C++ --------------------------------------------------
        try:
            CppOracle()
            print("C++ oracle    : WIRED")
            print("ERROR: C++ harness comparison is not implemented in this file.")
            print("       Refusing to report a result for the C++ leg.")
            self.report.unavailable.append("C++ (harness present but unimplemented)")
        except CoqOracleUnavailable as exc:
            print(f"C++ oracle    : UNAVAILABLE — {exc}")
            self.report.unavailable.append(f"C++ ({exc})")

        # --- Layer 2: Coq ---------------------------------------------------
        try:
            oracle = CoqOracle()
            print(f"Coq oracle    : WIRED (coqc, vm_compute over {len(checks)} cases)")
            print("Evaluating Coq kernel... (this invokes coqc and takes a while)")
            results = oracle.evaluate(checks)
            for i, agreed in enumerate(results):
                self.report.compared += 1
                if not agreed:
                    self.report.mismatches.append(
                        Mismatch(names[i], i, descriptions[i])
                    )
        except CoqOracleUnavailable as exc:
            print(f"Coq oracle    : UNAVAILABLE — {exc}")
            self.report.unavailable.append(f"Coq ({exc})")

        return self.report

    def print_summary(self) -> None:
        r = self.report
        print()
        print("=" * 70)
        print("DIFFERENTIAL FUZZING SUMMARY")
        print("=" * 70)
        print(f"Cases compared against an independent oracle: {r.compared}")
        print(f"Mismatches:                                   {len(r.mismatches)}")
        for note in r.unavailable:
            print(f"Not compared: {note}")
        print()

        if r.mismatches:
            print("MISMATCHES (CONSENSUS-CRITICAL):")
            for m in r.mismatches:
                print(f"  [{m.case_index}] {m.test_name}: {m.inputs}")
            print()
            print("ERROR: Differential fuzzing detected a consensus mismatch.")
        elif not r.conclusive:
            print("INCONCLUSIVE: no independent oracle was available.")
            print("Nothing was verified. This is NOT a passing result.")
        else:
            print("AGREEMENT: Python spec and Coq kernel agree on all compared cases.")
            print("Scope: ConvergenceRoot and SigmaCR01 only. This is evidence of")
            print("Python<->Coq agreement on sampled inputs. It is NOT a proof of")
            print("equivalence, and it says nothing about the C++ implementation.")
        print("=" * 70)


def main() -> int:
    iterations = int(os.environ.get("RIGOR_FUZZ_ITERATIONS", "16"))
    seed_env = os.environ.get("RIGOR_FUZZ_SEED")
    seed = int(seed_env) if seed_env else None

    fuzzer = DifferentialFuzzer(iterations=iterations, seed=seed)
    report = fuzzer.run()
    fuzzer.print_summary()

    if not report.ok:
        return 1
    if not report.conclusive:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
