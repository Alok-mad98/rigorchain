#!/usr/bin/env python3
"""Emit core/src/test/selection_golden_bridge.inc from phase3_golden_vectors.json."""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VEC = Path(os.environ["GOLDEN_VEC"]) if "GOLDEN_VEC" in os.environ else ROOT / "formal_verification" / "phase3_golden_vectors.json"
OUT = Path(os.environ["BRIDGE_OUT"]) if "BRIDGE_OUT" in os.environ else ROOT / "core" / "src" / "test" / "selection_golden_bridge.inc"


def main() -> None:
    data = json.loads(VEC.read_text())
    enc = [v for v in data["vectors"] if v["module"] == "SigmaEncoder"]
    a9c = [v for v in data["vectors"] if v["module"] == "WindowExclusion"]
    sig = [v for v in data["vectors"] if v["module"] == "SigmaPoW01"]
    hashk = [v for v in data["vectors"] if v["module"] == "HashKernel"]
    fips = [v for v in data["vectors"] if v["module"] == "Sha256Fips"]
    L = []
    L.append("// AUTO-GENERATED by formal_verification/tools/gen_cpp_bridge_header.py — DO NOT EDIT.")
    L.append("// Shared golden vectors for C++ differential tests (encoder, A-9-C exclusion, SHA-256d, FIPS SHA-256).")
    L.append("#include <cstdint>")
    L.append("#include <string>")
    L.append("#include <vector>")
    L.append("namespace rigor_golden {")
    L.append("struct EncVec { const char* id; const char* txid_hex; const char* croot_hex; const char* prev_hex; uint32_t height; const char* preimage_hex; const char* sigma_hex; };")
    L.append("struct A9CVec { const char* id; std::vector<std::string> candidates; std::vector<std::string> paid; std::vector<std::string> surviving; };")
    L.append("struct SigVec { const char* id; const char* txid_hex; const char* croot_hex; const char* prev_hex; uint32_t height; const char* sigma_hex; };")
    L.append("struct HashVec { const char* id; const char* payload_hex; const char* sha256d_hex; };")
    L.append("struct Sha256Vec { const char* id; const char* payload_hex; const char* sha256_hex; };")
    L.append("")
    L.append("static const EncVec kEnc[] = {")
    for v in enc:
        i, e = v["input"], v["expected"]
        L.append(
            f'  {{ "{v["id"]}", "{i["txid_hex"]}", "{i["convergence_root_hex"]}", '
            f'"{i["prev_block_hash_hex"]}", {int(i["height"])}u, "{e["preimage_hex"]}", "{e["sigma"]}" }},'
        )
    L.append("};")
    L.append("static const size_t kEncN = sizeof(kEnc)/sizeof(kEnc[0]);")
    L.append("")
    L.append("static const A9CVec kA9C[] = {")
    for v in a9c:
        i, e = v["input"], v["expected"]

        def vec(hs):
            return "{" + ", ".join(f'std::string("{h}")' for h in hs) + "}"

        L.append(
            f'  {{ "{v["id"]}", {vec(i["candidates_hex"])}, {vec(i["already_paid_hex"])}, {vec(e["surviving_hex"])} }},'
        )
    L.append("};")
    L.append("static const size_t kA9CN = sizeof(kA9C)/sizeof(kA9C[0]);")
    L.append("")
    L.append("static const SigVec kSig[] = {")
    for v in sig:
        i, e = v["input"], v["expected"]
        L.append(
            f'  {{ "{v["id"]}", "{i["txid_hex"]}", "{i["convergence_root_hex"]}", '
            f'"{i["prev_block_hash_hex"]}", {int(i["height"])}u, "{e["sigma"]}" }},'
        )
    L.append("};")
    L.append("static const size_t kSigN = sizeof(kSig)/sizeof(kSig[0]);")
    L.append("")
    L.append("static const HashVec kHash[] = {")
    for v in hashk:
        i, e = v["input"], v["expected"]
        L.append(f'  {{ "{v["id"]}", "{i["payload_hex"]}", "{e["sha256d"]}" }},')
    L.append("};")
    L.append("static const size_t kHashN = sizeof(kHash)/sizeof(kHash[0]);")
    L.append("")
    L.append("static const Sha256Vec kSha256[] = {")
    for v in fips:
        i, e = v["input"], v["expected"]
        L.append(f'  {{ "{v["id"]}", "{i["payload_hex"]}", "{e["sha256"]}" }},')
    L.append("};")
    L.append("static const size_t kSha256N = sizeof(kSha256)/sizeof(kSha256[0]);")
    L.append("} // namespace rigor_golden")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} enc={len(enc)} a9c={len(a9c)} sig={len(sig)} hash={len(hashk)} fips={len(fips)}")


if __name__ == "__main__":
    main()
